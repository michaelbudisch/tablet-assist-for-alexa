"""Static distribution contract for the optional ambient calendar."""
from pathlib import Path
import unittest
ROOT=Path(__file__).resolve().parents[1]
MAIN=ROOT/"custom_components"/"tablet_assist_for_alexa"
BUNDLE=ROOT/"tafa_app"/"bundle"/"tablet_assist_for_alexa"
class AmbientCalendarTest(unittest.TestCase):
    def test_same_optional_module_in_both_packages(self):
        for f in ("frontend/ambient_overview.js","frontend/ambient_night.js","__init__.py"):
            self.assertEqual((MAIN/f).read_bytes(),(BUNDLE/f).read_bytes())
    def test_no_direct_google_token_or_browser_microphone(self):
        js=(MAIN/"frontend/ambient_overview.js").read_text()
        self.assertIn('service:"get_events"',js)
        self.assertIn("calendar.familie",js)
        self.assertNotIn("getUserMedia",js)
        self.assertIn("hz-overview-construct",js)
        self.assertIn("hz-overview-cell-in",js)
        self.assertIn("hz-overview-edge",js)
        self.assertIn('class="edge-n"',js)
        self.assertNotIn('class="top"',js)
        self.assertIn("playBeam",js)
        self.assertIn("prefers-reduced-motion",js)
        self.assertIn("cancelAnimationFrame(beamFrame)",js)
        self.assertIn("entityEvents=id=>",js)
        self.assertIn('service:"get_events"',js)
        self.assertIn('card.h.callApi("GET",uri)',js)
        self.assertIn("mergeEvents(received||[],entityEvents(id))",js)
        self.assertIn("hz-overview-particles",js)
        self.assertIn("Shooting stars run FROM sphere nodes",js)
        self.assertIn("Nodes appear only after",js)
        self.assertIn('service:"get_forecasts"',js)
        self.assertIn("validPower=e=>",js)
        self.assertIn("hz-overview-forecast",js)
        self.assertIn("hz-overview-energy",js)
        self.assertIn("hz-overview-bottom",js)
        self.assertIn("<span>SO</span><span>MO</span>",js)
        self.assertIn("background:transparent!important",js)
        self.assertIn("data-next-event",js)
        self.assertIn("34vh,370px",js)
        self.assertIn("23vh,310px",js)
        self.assertIn("const positionSphere=()=>",js)
        self.assertIn("--hz-sphere-scale",js)
        self.assertIn("position:relative!important",js)
        self.assertIn("hz-overview-monthmark",js)
        self.assertIn("day.getDate()===1",js)
        self.assertIn("hz-overview-soft-in",js)
        self.assertIn("Math.max(.50,Math.min(.68,fit))",js)
        self.assertIn("position:relative!important;top:auto!important;left:auto!important",js)
        self.assertIn("const targetY=panelTop-14-radius",js)
        self.assertIn("const resolvePresenceId=states=>",js)
        self.assertIn("lastCalendarFingerprint",js)
        self.assertIn("hz-overview-lite-reveal",js)
        self.assertIn("const density=tablet?.75",js)
        self.assertIn("const interval=tablet?55:24",js)
        self.assertIn("host.dataset.overviewBuilding",js)
        self.assertIn("const segments=tablet?6:15",js)
        self.assertIn('const tablet=host.dataset.tablet==="1"',js)
        self.assertIn("annäherung",js)
        self.assertIn('value="sensor"',js)
        self.assertIn('value="time"',js)
        self.assertIn('value="either"',js)
        self.assertIn('min="0" step="any"',js)
        self.assertNotIn('min="15" max="180"',js)
        self.assertIn("cfg.idle>0",js)
        self.assertIn('open("sensor")',js)
        self.assertIn('cfg.dismiss!=="time")close()',js)
        self.assertIn("margin-top:clamp(52px,8vh,96px)!important",js)
        self.assertIn("background:transparent!important",js)
        self.assertNotIn("subscribeEvents",js)
        self.assertIn("host.dataset.ambientInfoState",js)
        self.assertNotIn("host.dataset.info",js)
        self.assertIn("event.stopPropagation()",js)
    def test_android_sphere_is_throttled_only_while_building(self):
        src=(MAIN/"frontend/ambient_night.js").read_text()
        self.assertIn('host.dataset.overviewBuilding==="1"',src)
        self.assertIn("building?40:android?31:15",src)
        self.assertIn("android?4:13",src)
    def test_ambient_status_not_an_entity_click_target(self):
        ambient=(MAIN/"frontend/ambient_night.js").read_text()
        self.assertIn('data-ambient-info-state="open"',ambient)
        self.assertNotIn('data-info="open"',ambient)
        self.assertNotIn("dataset.info",ambient)
    def test_optional_resource_is_registered(self):
        src=(MAIN/"__init__.py").read_text()
        self.assertIn('StaticPathConfig("/tablet_assist_for_alexa/ambient_overview.js"',src)
if __name__=="__main__":
    unittest.main()
