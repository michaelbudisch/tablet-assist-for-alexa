import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const prefix="custom_components/tablet_assist_for_alexa/frontend/";
const storage=new Map();
globalThis.localStorage={getItem:key=>storage.get(key)??null,setItem:(key,value)=>storage.set(key,String(value))};
const agent=value=>Object.defineProperty(globalThis,"navigator",{configurable:true,value:{userAgent:value}});
const read=name=>readFileSync(prefix+name,"utf8");
const importText=source=>import("data:text/javascript;base64,"+Buffer.from(source).toString("base64"));
const {selectTafaVisualDevice,VISUAL_BINDING_KEY}=await importText(read("visual_client.js"));
const ambientPrefix=read("ambient_profiles_client.js").split("export async function subscribeOwnAmbientProfile")[0];
const {deviceFor}=await importText(ambientPrefix+"\nexport {deviceFor};");
const oldId="a".repeat(32),newId="b".repeat(32),secondId="c".repeat(32);
const device={device_id:newId,user_id:"owner",sensors:{status:"sensor.tafa_b_rufwortstatus"}};
const identity={devices:[device]};
const admin={user:{is_admin:true}},regular={user:{is_admin:false}};
agent("Mozilla/5.0 (Linux; Android 9; SM-T590)");
storage.set(VISUAL_BINDING_KEY,oldId);
assert.equal(selectTafaVisualDevice(admin,identity).device_id,newId,"Android admin must recover stale visual ID");
assert.equal(storage.get(VISUAL_BINDING_KEY),newId);
storage.set("tafa.ambient.local_device.v1",oldId);
assert.equal(deviceFor({h:admin},[device]).toString(),newId,"Android must select sole new Ambient ID");
assert.equal(storage.get("tafa.ambient.local_device.v1"),newId);
agent("Mozilla/5.0 (Windows NT 10.0)");
storage.set(VISUAL_BINDING_KEY,oldId);
storage.set("tafa.ambient.local_device.v1",oldId);
assert.equal(selectTafaVisualDevice(admin,identity),null,"Desktop admin must not auto-bind another room");
assert.equal(deviceFor({h:admin},[device]),"","Desktop admin must not auto-bind Ambient");
assert.equal(selectTafaVisualDevice(regular,identity).device_id,newId,"Room user with one tablet can rebind");
assert.equal(deviceFor({h:regular},[device]),newId);
storage.set(VISUAL_BINDING_KEY,"none");
assert.equal(selectTafaVisualDevice(regular,identity),null,"Explicit opt-out must remain");
storage.set(VISUAL_BINDING_KEY,oldId);
agent("Android");
assert.equal(selectTafaVisualDevice(admin,{devices:[device,{...device,device_id:secondId}]}),null,"Ambiguous tablet selection must be rejected");
assert.equal(deviceFor({h:admin},[device,{...device,device_id:secondId}]),"","Ambiguous Ambient selection must be rejected");
const night=read("ambient_night.js");
assert.ok(night.includes("void subscribeVisual(deviceId)"),"Profile arrival must rebind visual stream");
assert.ok(night.includes("s.visualToken!==token"),"Stale asynchronous subscriptions must be discarded");
assert.ok(night.includes("s.visualToken=(s.visualToken||0)+1"),"Disposal must cancel pending subscriptions");
console.log("TAFA Android reinstall Ambient and visual binding tests passed");
